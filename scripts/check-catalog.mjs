import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const lock=JSON.parse(fs.readFileSync(path.join(root,'validation/contract-lock.json'),'utf8'));
if(lock.schema_version!==1||lock.kind!=='catalogs'||lock.contract_version!==1||!/^[a-f0-9]{40}$/.test(lock.commit)||Object.keys(lock.files).join()!=='catalogs.mjs')throw Error('Invalid pinned catalog contract');
const actual=createHash('sha256').update(fs.readFileSync(path.join(root,'validation/catalogs.mjs'))).digest('hex');
if(actual!==lock.files['catalogs.mjs'])throw Error(`Catalog rules differ from developer ${lock.commit}`);
const checks=await import('../validation/catalogs.mjs');
const config=JSON.parse(fs.readFileSync(path.join(root,'config/release-catalog.json'),'utf8'));
const check={tools:checks.checkTools,models:checks.checkModels,examples:checks.checkExamples}[config.kind];
if(!check)throw Error('Unsupported repository catalog kind');
check(root);
console.log(`Validated ${config.repository} using developer catalog contract ${lock.contract_version} (${lock.commit.slice(0,8)}).`);
