#!/usr/bin/env bash
# Check commit messages against the convention in README.md
# ("Commit message convention"). This is the single source of the rules:
# the local git hooks and the CI workflow all call this script.
#
# Usage:
#   check-commit-msg.sh --file <path> [--allow-autosquash]
#       Check one message stored in a file (commit-msg hook, PR title).
#   check-commit-msg.sh --revs <git rev-list arguments...>
#       Check every non-merge commit selected by the rev-list arguments
#       (pre-push hook, CI). Example: --revs origin/master..HEAD
#
# Exit status: 0 = all messages pass, 1 = at least one fails, 2 = usage error.

set -uo pipefail

TYPES='feat|fix|docs|refactor|sync|ci|chore'
SCOPE_RE='[a-z0-9][a-z0-9-]*(/[a-z0-9][a-z0-9-]*)*'
MAX_LEN=72

# Information that must never appear in a public commit message.
# Private IPv4 ranges and internal-only domains.
INTERNAL_RE='(^|[^0-9])(10\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}|172\.(1[6-9]|2[0-9]|3[01])\.[0-9]{1,3}\.[0-9]{1,3}|192\.168\.[0-9]{1,3}\.[0-9]{1,3})([^0-9]|$)|inhand\.design|gitlab\.inhand'

HEADER_RE="^(${TYPES})(\\(${SCOPE_RE}\\))?!?: (.+)$"

allow_autosquash=0
require_bilingual=0
failures=0

err() { printf '  - %s\n' "$*" >&2; }

# Remove comment lines and everything below the scissors line, the same way
# `git commit` cleans the message before storing it.
clean_message() {
  sed -e '/^# ------------------------ >8 ------------------------$/,$d' \
      -e '/^#/d' | sed -e 's/[[:space:]]*$//'
}

# check_one <label> <message>
check_one() {
  local label=$1 msg=$2
  local -a problems=()
  local header body_line n=0

  # Drop leading blank lines.
  msg=$(printf '%s\n' "$msg" | sed -e '/./,$!d')
  header=$(printf '%s\n' "$msg" | head -n 1)

  if [[ -z $header ]]; then
    problems+=("the message is empty")
  elif [[ $header =~ ^(fixup|squash|amend)!\  ]]; then
    if (( allow_autosquash )); then return 0; fi
    problems+=("'${header%% *}' commits must be squashed before pushing (git rebase -i --autosquash)")
  elif [[ $header =~ ^Revert\ \" ]]; then
    : # Accept messages generated by `git revert`.
  elif [[ ! $header =~ $HEADER_RE ]]; then
    problems+=("the first line must be '<type>(<scope>): <subject>'")
    if [[ $header =~ ^([A-Za-z0-9_-]+)(\(([^\)]*)\))?!?: ]]; then
      local t=${BASH_REMATCH[1]} s=${BASH_REMATCH[3]}
      if [[ ! $t =~ ^(${TYPES})$ ]]; then
        problems+=("unknown type '$t'; use one of: ${TYPES//|/, }")
      fi
      if [[ -n $s && ! $s =~ ^${SCOPE_RE}$ ]]; then
        problems+=("a scope may only contain lowercase letters, digits, '-' and '/'")
      fi
    else
      problems+=("no type found; examples: 'fix: ...', 'docs(mo62a): ...'")
    fi
  else
    local subject=${BASH_REMATCH[4]}
    subject=${subject% \[skip ci\]}
    if [[ ! $subject =~ ^[a-z] ]]; then
      problems+=("the subject must start with a lowercase letter")
    fi
    if [[ $subject =~ \.$ ]]; then
      problems+=("the subject must not end with a period")
    fi
  fi

  if (( ${#header} > MAX_LEN )); then
    problems+=("the first line is ${#header} characters; the limit is ${MAX_LEN}")
  fi

  # Line 2 must be blank when there is a body.
  local second
  second=$(printf '%s\n' "$msg" | sed -n '2p')
  if [[ -n $second ]]; then
    problems+=("leave the second line blank between the subject and the body")
  fi

  # Body lines: wrap at MAX_LEN. URLs and indented code are exempt.
  while IFS= read -r body_line; do
    n=$((n + 1))
    (( n <= 2 )) && continue
    if (( ${#body_line} > MAX_LEN )) && \
       [[ ! $body_line =~ https?:// && ! $body_line =~ ^(\ \ \ \ |$'\t') ]]; then
      problems+=("line $n is ${#body_line} characters; wrap the body at ${MAX_LEN}")
    fi
  done <<< "$msg"

  if printf '%s\n' "$msg" | grep -Eiq "$INTERNAL_RE"; then
    problems+=("the message contains internal information (private IP address or internal domain)")
  fi

  if (( require_bilingual )); then
    local markers en_count zh_count en_text zh_text field_count
    markers=$(printf '%s\n' "$msg" | grep -c '^Message:$' || true)
    en_count=$(printf '%s\n' "$msg" | grep -c '^  en: .\+' || true)
    zh_count=$(printf '%s\n' "$msg" | grep -c '^  zh: .\+' || true)
    field_count=$(printf '%s\n' "$msg" | sed -n '/^Message:$/,$p' | grep -c '^  [a-z][a-z]*:' || true)
    en_text=$(printf '%s\n' "$msg" | sed -n 's/^  en: //p')
    zh_text=$(printf '%s\n' "$msg" | sed -n 's/^  zh: //p')
    if (( markers != 1 || en_count != 1 || zh_count != 1 || field_count != 2 )); then
      problems+=("add one final Message block with exactly '  en:' and '  zh:' fields")
    else
      [[ $en_text =~ [A-Za-z] ]] || problems+=("Message.en must contain English text")
      printf '%s\n' "$zh_text" | grep -Pq '[\x{4e00}-\x{9fff}]' || problems+=("Message.zh must contain Chinese text")
    fi
  fi

  if (( ${#problems[@]} )); then
    failures=$((failures + 1))
    printf '\n✗ %s\n    %s\n' "$label" "$header" >&2
    local p
    for p in "${problems[@]}"; do err "$p"; done
    return 1
  fi
  return 0
}

usage() {
  sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//' >&2
  exit 2
}

[[ $# -ge 1 ]] || usage

case $1 in
  --file)
    [[ $# -ge 2 && -r $2 ]] || usage
    file=$2; shift 2
    while [[ $# -gt 0 ]]; do
      case $1 in
        --allow-autosquash) allow_autosquash=1 ;;
        --require-bilingual) require_bilingual=1 ;;
        *) usage ;;
      esac
      shift
    done
    check_one "commit message" "$(clean_message < "$file")"
    ;;
  --revs)
    shift
    [[ $# -ge 1 ]] || usage
    rev_args=()
    for arg in "$@"; do
      if [[ $arg == --require-bilingual ]]; then
        require_bilingual=1
      else
        rev_args+=("$arg")
      fi
    done
    (( ${#rev_args[@]} )) || usage
    mapfile -t commits < <(git rev-list --no-merges --reverse "${rev_args[@]}")
    for c in "${commits[@]}"; do
      check_one "commit ${c:0:12}" "$(git log -1 --format=%B "$c")"
    done
    ;;
  *) usage ;;
esac

if (( failures )); then
  cat >&2 <<'EOF'

The commit message does not follow the convention in README.md
("Commit message convention").

  To fix the last commit:      git commit --amend
  To fix older commits:        git rebase -i <base>   (choose "reword")
EOF
  exit 1
fi
exit 0
